"""Validate generated JSONL candidates and split trusted/provisional/rejected data."""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from typing import Any

REPOSITORY_ROOT = Path(__file__).resolve().parents[1]
if str(REPOSITORY_ROOT) not in sys.path:
    sys.path.insert(0, str(REPOSITORY_ROOT))

from src.data.schema import CADSample, parse_jsonl, write_jsonl
from src.data.validation import DatasetValidator, SampleValidationReport, ValidationPolicy
from src.data.validation_cache import ValidationCache
from src.env.mock_runner import MockRunner
from src.env.openscad_runner import CADExecutableNotFound, OpenSCADRunner


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, required=True, help="candidate JSONL generated by prepare_dataset.py")
    parser.add_argument("--backend", choices=("auto", "openscad", "analytic", "mock"), default="auto")
    parser.add_argument("--allow-analytic", action="store_true", help="admit exact analytic CSG records without an STL")
    parser.add_argument("--max-bbox-error", type=float, default=0.15)
    parser.add_argument("--max-volume-error", type=float, default=0.05)
    parser.add_argument("--workers", type=int, default=1, help="parallel OpenSCAD subprocesses; default is conservative")
    parser.add_argument("--accepted-output", type=Path)
    parser.add_argument("--provisional-output", type=Path)
    parser.add_argument("--rejected-output", type=Path)
    parser.add_argument("--report-output", type=Path)
    parser.add_argument("--cache", type=Path)
    parser.add_argument("--fail-on-rejected", action="store_true", help="exit with code 1 if any row fails validation")
    return parser


def _write_report(path: Path, records: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp")
    try:
        with temporary.open("w", encoding="utf-8", newline="\n") as stream:
            for record in records:
                stream.write(json.dumps(record, ensure_ascii=False, allow_nan=False) + "\n")
        temporary.replace(path)
    finally:
        temporary.unlink(missing_ok=True)


def _report_row(report: SampleValidationReport, cache_hit: bool) -> dict[str, Any]:
    verification = report.sample.verification
    return {
        "id": report.sample.id,
        "status": report.status,
        "accepted": report.accepted,
        "validation_backend": verification.validation_backend,
        "validation_runtime": report.sample.metadata.get("validation_runtime"),
        "target_bbox": verification.target_bbox,
        "actual_bbox": verification.actual_bbox,
        "bbox_relative_error": verification.bbox_relative_error,
        "volume_mm3": verification.volume_mm3,
        "is_watertight": verification.is_watertight,
        "components_count": verification.components_count,
        "euler_characteristic": verification.euler_characteristic,
        "validation_error": verification.validation_error,
        "code_sha256": report.sample.metadata.get("code_sha256"),
        "errors": report.errors,
        "warnings": report.warnings,
        "cache_hit": cache_hit,
    }


def main() -> int:
    parser = build_parser()
    args = parser.parse_args()
    if args.workers < 1:
        parser.error("--workers must be at least 1")
    if not args.input.is_file():
        parser.error(f"input JSONL does not exist: {args.input}")

    source = args.input.resolve()
    default_stem = source.stem + ".validation"
    accepted_path = args.accepted_output or source.with_name(default_stem + ".accepted.jsonl")
    provisional_path = args.provisional_output or source.with_name(default_stem + ".provisional.jsonl")
    rejected_path = args.rejected_output or source.with_name(default_stem + ".rejected.jsonl")
    report_path = args.report_output or source.with_name(default_stem + ".report.jsonl")
    cache_path = args.cache or source.with_name("." + source.stem + ".validation-cache.json")
    destinations = [accepted_path.resolve(), provisional_path.resolve(), rejected_path.resolve(), report_path.resolve()]
    cache_resolved = cache_path.resolve()
    if source in destinations or cache_resolved in destinations or cache_resolved == source:
        parser.error("input, outputs, and cache paths must be distinct")
    if len(set(destinations)) != len(destinations):
        parser.error("all output paths must be distinct")

    runner = None
    try:
        if args.backend == "mock":
            runner = MockRunner()
        elif args.backend == "openscad":
            runner = OpenSCADRunner()
        elif args.backend == "auto" and shutil.which("openscad"):
            runner = OpenSCADRunner()
    except CADExecutableNotFound as exc:
        parser.error(str(exc))

    try:
        policy = ValidationPolicy(
            max_bbox_relative_error=args.max_bbox_error,
            max_volume_relative_error=args.max_volume_error,
            accept_exact_analytic=args.allow_analytic,
        )
    except ValueError as exc:
        parser.error(str(exc))
    validator = DatasetValidator(runner=runner, policy=policy)
    cache = ValidationCache(cache_path, validator.cache_fingerprint)
    if cache.load_warning:
        print(f"[WARNING] {cache.load_warning}")

    samples: list[CADSample] = parse_jsonl(source)
    def validate_one(sample: CADSample) -> tuple[SampleValidationReport, bool]:
        cached = cache.get(sample)
        if cached is not None:
            return cached, True
        report = validator.validate(sample)
        cache.put(sample, report)
        return report, False

    # executor.map preserves row order; cache access and writes are lock-protected.
    if args.workers == 1:
        outcomes = [validate_one(sample) for sample in samples]
    else:
        with ThreadPoolExecutor(max_workers=args.workers, thread_name_prefix="cad-validate") as executor:
            outcomes = list(executor.map(validate_one, samples))
    reports = [outcome[0] for outcome in outcomes]
    cache_hits = [outcome[1] for outcome in outcomes]

    accepted: list[CADSample] = []
    provisional: list[CADSample] = []
    rejected: list[CADSample] = []
    rows: list[dict[str, Any]] = []
    for report, cache_hit in zip(reports, cache_hits):
        if report.accepted:
            accepted.append(report.sample)
        elif report.errors:
            rejected.append(report.sample)
        else:
            provisional.append(report.sample)
        rows.append(_report_row(report, cache_hit))

    write_jsonl(accepted_path, accepted)
    write_jsonl(provisional_path, provisional)
    write_jsonl(rejected_path, rejected)
    _write_report(report_path, rows)
    cache.save()
    backend_name = "none (static/analytic only)" if runner is None else type(runner).__name__
    print(
        f"Validation complete with {backend_name}: {len(accepted)} accepted, "
        f"{len(provisional)} provisional, {len(rejected)} rejected, "
        f"{sum(cache_hits)} cache hits."
    )
    print(f"Accepted:   {accepted_path}")
    print(f"Provisional:{provisional_path}")
    print(f"Rejected:   {rejected_path}")
    print(f"Report:     {report_path}")
    return 1 if args.fail_on_rejected and rejected else 0


if __name__ == "__main__":
    raise SystemExit(main())
