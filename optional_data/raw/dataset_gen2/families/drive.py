_GEAR_NAMES = (
    {"m": "module_m", "z": "teeth", "w": "face_w", "bore": "bore_d", "hub": "hub_d", "hubh": "hub_h"},
    {"m": "modul", "z": "n_teeth", "w": "width", "bore": "shaft_d", "hub": "boss_d", "hubh": "boss_h"},
    {"m": "gear_module", "z": "tooth_count", "w": "gear_w", "bore": "bore", "hub": "hub_dia", "hubh": "hub_len"},
)


def _gear_block(names: dict[str, str], *, hub: bool, light: int, keyway: bool, set_screw: bool) -> str:
    m = names["m"]
    z = names["z"]
    w = names["w"]
    bore = names["bore"]
    hub_d = names["hub"]
    hub_h = names["hubh"]
    lines = [
        "/* --- involute profile --- */",
        "pitch_r = " + m + " * " + z + " / 2;",
        "base_r = pitch_r * cos(pa);",
        "tip_r = pitch_r + " + m + ";",
        "root_r = pitch_r - 1.25 * " + m + ";",
        "flank_steps = 6;",
        "",
        "function inv_deg(a) = (tan(a) - a * PI / 180) * 180 / PI;",
        "function flank_r(i) = root_r + (tip_r - root_r) * i / flank_steps;",
        "function half_angle(r) = 90 / " + z + " + inv_deg(pa) - inv_deg(acos(min(1, base_r / r)));",
        "function tooth_pt(k, i, side) =",
        "    let (r = flank_r(i), a = k * 360 / " + z + " + side * half_angle(r))",
        "    [r * cos(a), r * sin(a)];",
        "",
        "module tooth_profile() {",
        "  polygon(points = [",
        "    for (k = [0 : " + z + " - 1])",
        "      each [",
        "        for (i = [0 : flank_steps]) tooth_pt(k, i, -1),",
        "        for (i = [flank_steps : -1 : 0]) tooth_pt(k, i, 1),",
        "        let (ta = (k + 0.5) * 360 / " + z + ")",
        "          [root_r * cos(ta), root_r * sin(ta)]",
        "      ]",
        "  ]);",
        "}",
    ]
    solid = [
        "module gear_disc() {",
        "  linear_extrude(height = " + w + ") tooth_profile();",
        "}",
    ]
    if hub:
        solid.append("")
        solid.append("module hub_boss() {")
        solid.append("  translate([0, 0, " + w + " - 1]) cylinder(h = " + hub_h + " + 1, d = " + hub_d + ");")
        solid.append("}")
    bore_depth = (w + " + " + hub_h + " + 3") if hub else (w + " + 3")
    set_reach = (hub_d + " / 2 + 3") if hub else "(root_r * 0.6)"
    cuts = [
        "  translate([0, 0, -1]) cylinder(h = " + bore_depth + ", d = " + bore + ");",
    ]
    if light:
        cuts.append("  /* lightening holes in the web */")
        cuts.append(
            "  for (i = [0 : %d - 1]) rotate([0, 0, i * 360 / %d]) translate([light_r, 0, -1])\n"
            "    cylinder(h = %s + 3, d = light_d);" % (light, light, w)
        )
    if keyway:
        cuts.append("  /* keyway on the bore */")
        cuts.append(
            "  translate([-" + bore + " / 2 - 1, -key_w / 2, -1]) cube([key_h + 1, key_w, "
            + bore_depth + "]);"
        )
    if set_screw:
        cuts.append("  /* set screw, drilled radially */")
        cuts.append(
            "  translate([-1, 0, set_z]) rotate([0, 90, 0]) cylinder(h = " + set_reach + ", d = set_d);"
        )
    body = list(lines)
    body.append("")
    body.extend(solid)
    body.append("")
    body.append("difference() {")
    if hub:
        body.append("  union() {")
        body.append("    gear_disc();")
        body.append("    hub_boss();")
        body.append("  }")
    else:
        body.append("  gear_disc();")
    body.extend(cuts)
    body.append("}")
    return "\n".join(body)


def build_spur_gears(index: int) -> Part:
    rng = Rng("spur_gears", index)
    names = rng.choice(_GEAR_NAMES)
    module_m = rng.grid([1.0, 1.25, 1.5, 2.0, 2.5, 3.0])
    teeth = rng.integer(12, 48)
    width = rng.grid([6.0, 8.0, 10.0, 12.0, 15.0, 16.0, 20.0])
    pitch_r = module_m * teeth / 2
    tip_d = 2 * (pitch_r + module_m)
    root_d = 2 * (pitch_r - 1.25 * module_m)
    if root_d < 10:  # too small for a hub
        teeth = min(48, teeth + 6)
        pitch_r = module_m * teeth / 2
        tip_d = 2 * (pitch_r + module_m)
        root_d = 2 * (pitch_r - 1.25 * module_m)
    bore_d = rng.grid([5.0, 6.0, 6.35, 8.0, 10.0, 12.0, 14.0, 16.0])
    bore_d = min(bore_d, round(root_d * 0.35, 2))
    hub = rng.chance(0.7) and root_d >= 26
    hub_d = min(round(root_d * rng.uniform(0.55, 0.72), 1), root_d - 3) if hub else 0.0
    hub_d = max(hub_d, bore_d + 6) if hub else 0.0
    hub_h = rng.grid([4.0, 6.0, 8.0, 10.0]) if hub else 0.0
    light = 0
    light_d = 0.0
    light_r = 0.0
    if hub and root_d >= 46 and rng.chance(0.5):
        light = rng.choice([3, 4, 5, 6])
        light_d = min(round(root_d * 0.12, 1), 12.0)
        light_r = round((hub_d + root_d) / 4, 1)
        if not (light_r - light_d / 2 > hub_d / 2 + 1.5 and light_r + light_d / 2 < root_d / 2 - 1.5):
            light = 0
    keyway = rng.chance(0.3) and bore_d >= 8
    set_screw = rng.chance(0.45)
    height = width + hub_h

    builder = ScadBuilder(
        "Spur gear",
        f"m={fmt(module_m)} z={teeth}, {fmt(tip_d)} mm tip diameter x {fmt(height)} mm",
    )
    builder.param(names["m"], module_m, "module")
    builder.param(names["z"], teeth, "number of teeth")
    builder.param(names["w"], width, "face width")
    builder.param("pa", 20.0, "pressure angle, deg")
    builder.param(names["bore"], bore_d, "shaft bore")
    if hub:
        builder.param(names["hub"], hub_d, "hub diameter")
        builder.param(names["hubh"], hub_h, "hub above the face")
    if light:
        builder.param("light_d", light_d, "lightening hole diameter")
        builder.param("light_r", light_r, "lightening hole pitch radius")
    if keyway:
        builder.param("key_w", 3.0 if bore_d < 12 else 5.0, "keyway width")
        builder.param("key_h", 1.4 if bore_d < 12 else 2.3, "keyway depth")
    if set_screw:
        builder.param("set_d", 3.4 if bore_d < 10 else 4.5, "set screw tap hole")
        builder.param("set_z", round(width + max(hub_h, 2.0) * 0.5, 1), "set screw height")
    builder.section(_gear_block(names, hub=bool(hub), light=light, keyway=keyway, set_screw=set_screw))
    code = builder.render()

    bbox = (float(tip_d), float(tip_d), float(height))
    features_ru = [
        f"модуль {fmt(module_m)}, число зубьев {teeth}",
        f"делительный диаметр {fmt(2 * pitch_r)} мм",
    ]
    features_en = [
        f"module {fmt(module_m)}, {teeth} teeth",
        f"{fmt(2 * pitch_r)} mm pitch diameter",
    ]
    features_ru.append(f"посадочное отверстие {fmt(bore_d)} мм")
    features_en.append(f"{fmt(bore_d)} mm bore")
    if hub:
        features_ru.append(f"ступица {fmt(hub_d)} мм, выступает на {fmt(hub_h)} мм")
        features_en.append(f"{fmt(hub_d)} mm hub, {fmt(hub_h)} mm proud of the face")
    if light:
        features_ru.append(f"{ru_count(light, 'окно', 'окна', 'окон')} для облегчения на радиусе {fmt(light_r)}")
        features_en.append(f"{en_count(light)} lightening holes on a {fmt(light_r)} mm radius")
    if keyway:
        features_ru.append("в отверстии шпоночный паз")
        features_en.append("a keyway in the bore")
    if set_screw:
        features_ru.append("резьбовое отверстие под стопорный винт сбоку")
        features_en.append("a radial set screw hole")
    return _finish(
        rng,
        family="spurgears",
        variant=f"m{fmt(module_m)}" + ("_hub" if hub else "") + ("_holes" if light else ""),
        code=code,
        bbox=bbox,
        params={
            "module": module_m,
            "teeth": teeth,
            "face_width": width,
            "bore_d": bore_d,
            "hub_d": hub_d,
            "height": height,
        },
        ru_nouns=SPUR_RU,
        en_nouns=SPUR_EN,
        features_ru=features_ru,
        features_en=features_en,
    )


def build_helical_gears(index: int) -> Part:
    rng = Rng("helical_gears", index)
    names = rng.choice(_GEAR_NAMES)
    module_m = rng.grid([1.0, 1.5, 2.0, 2.5, 3.0])
    teeth = rng.integer(14, 42)
    width = rng.grid([10.0, 12.0, 15.0, 18.0, 20.0])
    helix = rng.grid([12.0, 15.0, 18.0, 20.0, 23.0, 25.0])
    pitch_r = module_m * teeth / 2
    tip_d = 2 * (pitch_r + module_m)
    root_d = 2 * (pitch_r - 1.25 * module_m)
    twist = round(math.degrees(math.atan(math.tan(math.radians(helix))) * width / (pitch_r)), 2)
    bore_d = min(rng.grid([6.0, 8.0, 10.0, 12.0, 14.0]), round(root_d * 0.32, 2))
    hub = root_d >= 30
    hub_d = max(round(root_d * 0.62, 1), bore_d + 6) if hub else 0.0
    hub_h = rng.grid([5.0, 8.0]) if hub else 0.0
    height = width + hub_h

    builder = ScadBuilder(
        "Helical gear",
        f"m={fmt(module_m)} z={teeth}, helix {fmt(helix)} deg, {fmt(tip_d)} mm x {fmt(height)} mm",
    )
    builder.param(names["m"], module_m, "normal module")
    builder.param(names["z"], teeth, "number of teeth")
    builder.param(names["w"], width, "face width")
    builder.param("pa", 20.0, "pressure angle, deg")
    builder.param("helix", helix, "helix angle, deg")
    builder.param("twist", twist, "total twist over the face, deg")
    builder.param("slices", max(4, int(round(twist / 3.0))), "twist divisions")
    builder.param(names["bore"], bore_d, "shaft bore")
    if hub:
        builder.param(names["hub"], hub_d, "hub diameter")
        builder.param(names["hubh"], hub_h, "hub above the face")
    builder.param("set_d", 4.5, "set screw tap hole")
    builder.param("set_z", round(width + max(hub_h, 2.0) * 0.5, 1), "set screw height")

    block = _gear_block(names, hub=hub, light=0, keyway=False, set_screw=True)
    block = block.replace(
        "  linear_extrude(height = " + names["w"] + ") tooth_profile();",
        "  linear_extrude(height = " + names["w"] + ", twist = twist, slices = slices) tooth_profile();",
    )
    builder.section(block)
    code = builder.render()

    bbox = (float(tip_d), float(tip_d), float(height))
    features_ru = [
        f"модуль {fmt(module_m)}, зубьев {teeth}, наклон зуба {fmt(helix)}°",
        f"закрутка по ширине {fmt(twist)}° на {fmt(width)} мм",
    ]
    features_en = [
        f"module {fmt(module_m)}, {teeth} teeth, {fmt(helix)} deg helix",
        f"{fmt(twist)} deg of twist over the {fmt(width)} mm face",
    ]
    features_ru.append(f"отверстие под вал {fmt(bore_d)} мм")
    features_en.append(f"{fmt(bore_d)} mm shaft bore")
    if hub:
        features_ru.append(f"ступица {fmt(hub_d)} мм со стопорным винтом")
        features_en.append(f"{fmt(hub_d)} mm hub with a set screw")
    return _finish(
        rng,
        family="helicalgears",
        variant=f"helix{fmt(helix, 0)}",
        code=code,
        bbox=bbox,
        params={
            "module": module_m,
            "teeth": teeth,
            "face_width": width,
            "helix_deg": helix,
            "twist_deg": twist,
            "bore_d": bore_d,
            "height": height,
        },
        ru_nouns=HELICAL_RU,
        en_nouns=HELICAL_EN,
        features_ru=features_ru,
        features_en=features_en,
    )


