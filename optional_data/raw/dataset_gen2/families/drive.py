# NEMA motor mount plates
# ---------------------------------------------------------------------------

_MOTOR_NAMES = (
    {"pw": "plate_w", "pd": "plate_d", "pt": "plate_t", "pat": "pattern", "ph": "pilot_d"},
    {"pw": "base_x", "pd": "base_y", "pt": "thick", "pat": "bolt_pitch", "ph": "boss_hole"},
    {"pw": "mount_w", "pd": "mount_d", "pt": "mat_t", "pat": "motor_pitch", "ph": "center_bore"},
)


def build_motor_mounts(index: int) -> Part:
    rng = Rng("motor_mounts", index)
    names = rng.choice(_MOTOR_NAMES)
    frame = rng.choice(("NEMA17", "NEMA17", "NEMA23", "NEMA23", "NEMA34"))
    pattern, pilot, motor_screw, shaft = NEMA_TABLE[frame]
    edge_x = rng.grid([7.0, 8.0, 10.0, 12.0, 15.0])
    edge_y = rng.grid([7.0, 8.0, 10.0, 12.0, 15.0])
    plate_w = round(pattern + 2 * edge_x, 2)
    plate_d = round(pattern + 2 * edge_y, 2)
    plate_t = rng.grid([5.0, 6.0, 8.0, 10.0, 12.0])
    variant = rng.choice(("plate", "plate", "slots", "flanged", "boss"))
    second_d = rng.grid([3.4, 4.5, 5.5, 6.6])
    counterbore = motor_screw <= 4.5 and plate_t >= 5.0 and rng.chance(0.55)
    boss = variant == "boss"
    boss_h = rng.grid([2.0, 3.0, 4.0]) if boss else 0.0
    wall_h = 0.0
    wall = 0.0
    if variant == "flanged":
        wall_h = rng.grid([30.0, 40.0, 50.0, 60.0])
        wall = rng.grid([5.0, 6.0, 8.0])
        if wall_h < 2 * second_d + 8 or wall_h <= plate_t + 4:
            variant, wall_h, wall = "plate", 0.0, 0.0
    if variant == "slots":
        slot_l = rng.grid([16.0, 20.0, 25.0])
        slot_span = slot_l - second_d
        slot_outer = round(plate_w / 2 - 4.0, 2)
        slot_mid = round(slot_outer - slot_span / 2, 2)
        if slot_mid - slot_span / 2 - second_d / 2 < pilot / 2 + 3.0 or slot_mid + slot_span / 2 > slot_outer + 0.01:
            variant = "plate"
    second_pattern = rng.choice(("inset_holes", "inset_holes", "bolt_circle", "none"))
    if variant in ("slots", "flanged"):
        second_pattern = "none"

    builder = ScadBuilder(
        "Motor mount plate",
        f"{frame}, {fmt(plate_w)} x {fmt(plate_d)} x {fmt(plate_t + boss_h + wall_h)} mm",
    )
    builder.param(names["pw"], plate_w, "plate length, X")
    builder.param(names["pd"], plate_d, "plate width, Y")
    builder.param(names["pt"], plate_t, "plate thickness")
    builder.param(names["pat"], pattern, f"{frame} bolt spacing")
    builder.param("motor_d", motor_screw, f"{frame} screw clearance")
    builder.param(names["ph"], pilot, "pilot boss bore")
    if counterbore:
        builder.param("cb_d", round(motor_screw + 3.6, 1), "counterbore seat")
        builder.param("cb_h", round(min(plate_t - 2.0, motor_screw * 0.55), 2), "counterbore depth")
    if boss:
        builder.param("boss_d", round(pilot + 8.0, 1), "raised pilot ring")
        builder.param("boss_h", boss_h, "raised pilot ring height")
    if second_pattern != "none" or variant == "flanged":
        builder.param("second_d", second_d, "second fastener hole")
    if second_pattern == "bolt_circle":
        builder.param("bc_r", round(min(plate_w, plate_d) * 0.32, 1), "second bolt circle radius")
        builder.param("bc_n", rng.choice([4.0, 6.0, 8.0]), "second bolt circle count")
    if variant == "slots":
        builder.param("slot_l", slot_l, "tension slot length")
    if variant == "flanged":
        builder.param("wall_h", wall_h, "upright height")
        builder.param("wall_t", wall, "upright thickness")

    lines = [
        "module motor_holes() {",
        "  for (sx = [-1, 1]) for (sy = [-1, 1])",
        "    translate([sx * " + names["pat"] + " / 2, sy * " + names["pat"] + " / 2, -1])",
        "      cylinder(h = " + names["pt"] + " + 2, d = motor_d);",
        "}",
    ]
    if counterbore:
        lines.extend(
            [
                "module motor_counterbores() {",
                "  for (sx = [-1, 1]) for (sy = [-1, 1])",
                "    translate([sx * " + names["pat"] + " / 2, sy * " + names["pat"] + " / 2, " + names["pt"] + " - cb_h])",
                "      cylinder(h = cb_h + 0.6, d = cb_d);",
                "}",
            ]
        )
    if boss:
        lines.extend(
            [
                "module pilot_ring() {",
                "  translate([0, 0, " + names["pt"] + " - 1]) cylinder(h = boss_h + 1, d = boss_d);",
                "}",
            ]
        )
    if variant == "slots":
        lines.extend(
            [
                "module tension_slot(dx) {",
                "  hull() {",
                "    translate([dx - (slot_l - second_d) / 2, 0, -1]) cylinder(h = " + names["pt"] + " + 2, d = second_d);",
                "    translate([dx + (slot_l - second_d) / 2, 0, -1]) cylinder(h = " + names["pt"] + " + 2, d = second_d);",
                "  }",
                "}",
            ]
        )
    if variant == "flanged":
        lines.extend(
            [
                "module upright() {",
                "  /* wall sunk 1 mm into the plate for a positive overlap */",
                "  translate([" + names["pw"] + " / 2 - wall_t, -" + names["pd"] + " / 2 + wall_t, " + names["pt"] + " - 1])",
                "    cube([wall_t, " + names["pd"] + " - 2 * wall_t, wall_h - " + names["pt"] + " + 1]);",
                "}",
            ]
        )

    lines.extend(["", "difference() {", "  union() {", "    plate();"])
    if boss:
        lines.append("    pilot_ring();")
    if variant == "flanged":
        lines.append("    upright();")
    lines.append("  }")
    lines.append("  motor_holes();")
    lines.append(
        "  translate([0, 0, -1]) cylinder(h = " + names["pt"] + (" + boss_h" if boss else "") + " + 2, d = " + names["ph"] + ");"
    )
    if counterbore:
        lines.append("  motor_counterbores();")
    if second_pattern == "inset_holes":
        inset_x = round(plate_w / 2 - edge_x / 2 - 1.5, 2)
        inset_y = round(plate_d / 2 - edge_y / 2 - 1.5, 2)
        lines.append("  for (sx = [-1, 1]) for (sy = [-1, 1])")
        lines.append(
            "    translate([sx * " + fmt(inset_x) + ", sy * " + fmt(inset_y) + ", -1]) cylinder(h = " + names["pt"] + " + 2, d = second_d);"
        )
    if second_pattern == "bolt_circle":
        lines.append(
            "  for (i = [0 : bc_n - 1]) rotate([0, 0, i * 360 / bc_n]) translate([bc_r, 0, -1])"
            "    cylinder(h = " + names["pt"] + " + 2, d = second_d);"
        )
    if variant == "slots":
        lines.append("  tension_slot(-" + fmt(slot_mid) + ");")
        lines.append("  tension_slot(" + fmt(slot_mid) + ");")
    if variant == "flanged":
        lines.append("  for (i = [0 : 2])")
        lines.append(
            "    translate([" + names["pw"] + " / 2 - wall_t - 1, (i - 1) * wall_h * 0.3, " + names["pt"] + " + wall_h * 0.45])"
            " rotate([0, 90, 0]) cylinder(h = wall_t + 2, d = second_d);"
        )
    lines.append("}")
    lines.insert(0, "module plate() {")
    lines.insert(1, "  translate([-" + names["pw"] + " / 2, -" + names["pd"] + " / 2, 0]) cube([" + names["pw"] + ", " + names["pd"] + ", " + names["pt"] + "]);")
    lines.insert(2, "}")
    lines.insert(3, "")
    builder.section("\n".join(lines))
    code = builder.render()

    bbox = (float(plate_w), float(plate_d), float(max(plate_t + boss_h, wall_h)))
    features_ru = [f"крепёж {frame} с межосевым {fmt(pattern)} мм"]
    features_en = [f"{frame} pattern, {fmt(pattern)} mm bolt spacing"]
    features_ru.append(f"центральное отверстие под буртик {fmt(pilot)} мм")
    features_en.append(f"{fmt(pilot)} mm pilot bore")
    features_ru.append(f"толщина плиты {fmt(plate_t)} мм")
    features_en.append(f"{fmt(plate_t)} mm plate")
    if boss:
        features_ru.append(f"кольцевой буртик высотой {fmt(boss_h)} мм под центровку")
        features_en.append(f"a {fmt(boss_h)} mm raised pilot ring for centring")
    if variant == "flanged":
        features_ru.append(f"стойка высотой {fmt(wall_h)} мм с тремя отверстиями под крепёж")
        features_en.append(f"a {fmt(wall_h)} mm upright with three cross holes")
    if variant == "slots":
        features_ru.append(f"два паза длиной {fmt(slot_l)} мм под натяжение ремня")
        features_en.append(f"two {fmt(slot_l)} mm belt tension slots")
    if second_pattern == "bolt_circle":
        features_ru.append("вторая окружность отверстий под ответный фланец")
        features_en.append("a second bolt circle for the mating flange")
    if second_pattern == "inset_holes":
        features_ru.append("четыре отверстия по углам под крепление к раме")
        features_en.append("four corner holes for the frame")
    if counterbore:
        features_ru.append("цековки под головки винтов")
        features_en.append("counterbores for the screw heads")
    return _finish(
        rng,
        family="motormounts",
        variant=f"{frame.lower()}_{variant}",
        code=code,
        bbox=bbox,
        params={
            "frame": 17.0 if frame == "NEMA17" else (23.0 if frame == "NEMA23" else 34.0),
            "pattern": pattern,
            "pilot_d": pilot,
            "plate_w": plate_w,
            "plate_d": plate_d,
            "plate_t": plate_t,
            "height": bbox[2],
        },
        ru_nouns=MOTOR_RU,
        en_nouns=MOTOR_EN,
        features_ru=features_ru,
        features_en=features_en,
    )
