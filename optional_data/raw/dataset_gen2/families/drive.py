def build_pulleys(index: int) -> Part:
    rng = Rng("pulleys", index)
    names = rng.choice(_PULLEY_NAMES)
    profile = rng.choice(("GT2", "GT2", "GT2", "GT3", "T5", "HTD5"))
    pitch, drop, groove_h, tooth_w = BELT_TABLE[profile]
    teeth = rng.choice([14, 16, 18, 20, 22, 24, 30, 36, 40]) if profile != "T5" else rng.choice(
        [10, 12, 14, 16, 18, 20, 24, 30]
    )
    pitch_d = round(pitch * teeth / math.pi, 2)
    tip_d = round(pitch_d - drop, 2)          # tip circle of the pulley
    root_d = round(tip_d - 2 * groove_h, 2)   # groove bottom circle
    belt_w = rng.grid([6.0, 9.0, 10.0, 11.0, 15.0, 16.0, 20.0])
    flanged = rng.chance(0.75) and tip_d >= 12
    flange_t = rng.grid([1.2, 1.5, 2.0]) if flanged else 0.0
    flange_d = round(tip_d + (2.0 if profile in ("GT2", "GT3") else 3.0), 2) if flanged else tip_d
    hub_h = rng.grid([4.0, 6.0, 8.0, 10.0])
    hub_d = round(min(tip_d - 2.5, max(tip_d * 0.5, 12.0)), 2)
    bore_d = min(rng.grid([5.0, 6.0, 6.35, 8.0, 10.0, 12.0]), round(hub_d * 0.42, 2))
    # the hub runs through the whole pulley and protrudes by hub_h on top
    bottom_z = round(-flange_t, 2)
    top_z = round(belt_w + flange_t + hub_h, 2)
    height = round(top_z - bottom_z, 2)
    set_screw = rng.chance(0.7)
    keyway = rng.chance(0.25) and bore_d >= 8
    ring_holes = rng.chance(0.3) and hub_h >= 6 and flange_d - hub_d >= 10

    builder = ScadBuilder(
        "Timing pulley",
        f"{profile} {teeth}T, pitch {fmt(pitch, 3)} mm, {fmt(flange_d)} mm x {fmt(height)} mm",
    )
    builder.param(names["p"], pitch, "belt pitch")
    builder.param(names["z"], teeth, "number of grooves")
    builder.param(names["w"], belt_w, "belt width between the flanges")
    builder.param("tip_d", tip_d, "tip circle diameter")
    builder.param("root_d", root_d, "groove bottom diameter")
    builder.param("groove_h", groove_h, "groove depth")
    builder.param("tooth_w", tooth_w, "groove width at the tip circle")
    if flanged:
        builder.param(names["fd"], flange_d, "flange diameter")
        builder.param(names["fl"], flange_t, "flange thickness")
        builder.param("spigot_d", round(root_d - 1.6, 2), "flange spigot, sunk into the rim")
        builder.param("spigot_h", 1.2, "spigot depth into the rim")
    builder.param(names["bore"], bore_d, "shaft bore")
    builder.param("hub_d", hub_d, "hub diameter")
    builder.param("hub_h", hub_h, "hub above the flange")
    builder.param("bottom_z", bottom_z, "lowest point of the pulley")
    builder.param("top_z", top_z, "highest point of the pulley")
    if set_screw:
        builder.param("set_d", 3.4 if bore_d < 10 else 4.5, "set screw tap hole")
    if keyway:
        builder.param("key_w", 3.0, "keyway width")
        builder.param("key_h", 1.4, "keyway depth")
    if ring_holes:
        builder.param("ring_d", 2.8, "clamp screw hole")
        builder.param("ring_r", round((hub_d + root_d) / 4 - 1.0, 1), "clamp screw radius")

    lines = [
        "module rim() {",
        "  cylinder(h = " + names["w"] + ", d = tip_d);",
        "}",
        "",
        "module groove_cutter() {",
        "  /* belt tooth groove: deeper than wide, cut through the belt width */",
        "  translate([root_d / 2, 0, 0])",
        "    linear_extrude(height = " + names["w"] + ")",
        "      polygon(points = [[-0.6, -tooth_w * 0.42], [groove_h + 0.6, -tooth_w * 0.6],",
        "                        [groove_h + 0.6, tooth_w * 0.6], [-0.6, tooth_w * 0.42]]);",
        "}",
    ]
    if flanged:
        lines.extend(
            [
                "",
                "module flanges() {",
                "  translate([0, 0, -" + names["fl"] + "]) cylinder(h = " + names["fl"] + ", d = " + names["fd"] + ");",
                "  translate([0, 0, " + names["w"] + "]) cylinder(h = " + names["fl"] + ", d = " + names["fd"] + ");",
                "  translate([0, 0, -spigot_h]) cylinder(h = spigot_h + 0.6, d = spigot_d);",
                "  translate([0, 0, " + names["w"] + " - 0.6]) cylinder(h = spigot_h + 0.6, d = spigot_d);",
                "}",
            ]
        )
    lines.extend(
        [
            "",
            "module hub() {",
            "  translate([0, 0, bottom_z]) cylinder(h = top_z - bottom_z, d = hub_d);",
            "}",
            "",
            "difference() {",
            "  union() {",
            "    rim();",
            "    hub();",
        ]
    )
    if flanged:
        lines.append("    flanges();")
    lines.append("  }")
    lines.append("  for (i = [0 : " + names["z"] + " - 1]) rotate([0, 0, i * 360 / " + names["z"] + "]) groove_cutter();")
    lines.append(
        "  translate([0, 0, bottom_z - 1]) cylinder(h = top_z - bottom_z + 2, d = " + names["bore"] + ");"
    )
    if set_screw:
        lines.append(
            "  translate([-1, 0, top_z - hub_h * 0.5]) rotate([0, 90, 0]) cylinder(h = hub_d / 2 + 3, d = set_d);"
        )
    if keyway:
        lines.append(
            "  translate([-" + names["bore"] + " / 2 - 1, -key_w / 2, bottom_z - 1])\n"
            "    cube([key_h + 1, key_w, top_z - bottom_z + 2]);"
        )
    if ring_holes:
        lines.append(
            "  for (i = [0 : 5]) rotate([0, 0, i * 60]) translate([ring_r, 0, top_z - hub_h - 1])\n"
            "    cylinder(h = hub_h + 2, d = ring_d);"
        )
    lines.append("}")
    builder.section("\n".join(lines))
    code = builder.render()

    bbox = (float(flange_d), float(flange_d), float(height))
    features_ru = [f"профиль {profile}, {teeth} зубьев, шаг {fmt(pitch, 3)} мм"]
    features_en = [f"{profile} profile, {teeth} grooves, {fmt(pitch, 3)} mm pitch"]
    features_ru.append(f"посадочное отверстие {fmt(bore_d)} мм, ступица {fmt(hub_d)} мм")
    features_en.append(f"{fmt(bore_d)} mm bore, {fmt(hub_d)} mm hub")
    if flanged:
        features_ru.append("бортики с двух сторон, чтобы ремень не сходил")
        features_en.append("flanges on both sides to keep the belt on track")
    if set_screw:
        features_ru.append("отверстие под стопорный винт в ступице")
        features_en.append("a set screw hole in the hub")
    if ring_holes:
        features_ru.append("шесть отверстий в ступице под стяжные винты")
        features_en.append("six clamp screw holes in the hub")
    if keyway:
        features_ru.append("шпоночный паз в отверстии")
        features_en.append("a keyway in the bore")
    return _finish(
        rng,
        family="pulleys",
        variant=f"{profile}{teeth}" + ("_flanged" if flanged else ""),
        code=code,
        bbox=bbox,
        params={
            "pitch": pitch,
            "teeth": teeth,
            "pitch_d": pitch_d,
            "outer_d": flange_d,
            "belt_width": belt_w,
            "bore_d": bore_d,
            "height": height,
        },
        ru_nouns=PULLEY_RU,
        en_nouns=PULLEY_EN,
        features_ru=features_ru,
        features_en=features_en,
    )


