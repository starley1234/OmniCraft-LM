def _finish(
    rng: Rng,
    *,
    family: str,
    variant: str,
    code: str,
    bbox: tuple[float, float, float],
    params: dict[str, float],
    ru_nouns: tuple[str, ...],
    en_nouns: tuple[str, ...],
    features_ru: list[str],
    features_en: list[str],
) -> Part:
    prompt_ru, prompt_en = build_prompt(
        rng,
        ru_nouns=ru_nouns,
        en_nouns=en_nouns,
        bbox=bbox,
        ru_feature_sentences=[s[0].upper() + s[1:] + "." for s in features_ru],
        en_feature_sentences=[s[0].upper() + s[1:] + "." for s in features_en],
        feature_count=rng.integer(2, 3),
    )
    return Part(
        family=family,
        variant=variant,
        code=code,
        bbox=bbox,
        params=params,
        prompt_ru=prompt_ru,
        prompt_en=prompt_en,
    )


