_RACK_NAMES = (
    {"l": "length", "w": "width", "h": "height", "m": "module_m", "t": "back_t"},
    {"l": "rack_len", "w": "rack_w", "h": "rack_h", "m": "modul", "t": "body_t"},
    {"l": "bar_len", "w": "bar_w", "h": "bar_h", "m": "gear_module", "t": "base_t"},
)


def build_gear_racks(index: int) -> Part:
    rng = Rng("gear_racks", index)
    names = rng.choice(_RACK_NAMES)
    module_m = rng.grid([1.0, 1.25, 1.5, 2.0, 2.5, 3.0, 4.0])
    pitch = math.pi * module_m
    teeth = rng.integer(10, 34)
    overhang = rng.grid([8.0, 10.0, 12.0, 16.0, 20.0])
    # the corpus contract caps any axis at 250 mm: trim the tooth count
    max_teeth = int((250.0 - overhang) // pitch)
    teeth = max(10, min(teeth, max_teeth))
    length = round(teeth * pitch + overhang, 2)
    height = round(rng.grid([10.0, 12.0, 14.0, 16.0, 18.0, 20.0]) + module_m, 2)
    width = rng.grid([12.0, 15.0, 16.0, 20.0, 25.0, 30.0])
    addendum = module_m
    body_h = round(height - addendum, 2)
    tooth_tip = round(pitch / 2 - 2 * addendum * math.tan(math.radians(20)), 2)
    tooth_root = round(pitch / 2 + 2 * 1.25 * module_m * math.tan(math.radians(20)), 2)
    if tooth_tip < 0.7 * module_m:
        module_m = round(module_m * 0.8, 2)
        pitch = math.pi * module_m
        body_h = round(height - module_m, 2)
        tooth_tip = round(pitch / 2 - 2 * module_m * math.tan(math.radians(20)), 2)
        tooth_root = round(pitch / 2 + 2.5 * module_m * math.tan(math.radians(20)), 2)
    holes = rng.choice([0, 2, 2, 3, 4])
    thread_d = rng.grid([4.5, 5.5, 6.6])
    margin = rng.grid([8.0, 10.0, 12.0])

    builder = ScadBuilder("Gear rack", f"m={fmt(module_m)} z={teeth}, {fmt(length)} x {fmt(width)} x {fmt(height)} mm")
    builder.param(names["l"], length, "rack length, X")
    builder.param(names["w"], width, "rack width, Y")
    builder.param(names["h"], height, "overall height, Z")
    builder.param(names["m"], module_m, "module")
    builder.param(names["t"], body_h, "tooth root line height")
    builder.param("pitch", round(pitch, 3), "circular pitch")
    builder.param("tip_w", tooth_tip, "tooth thickness at the tip")
    builder.param("root_w", tooth_root, "tooth thickness at the root line")
    if holes:
        builder.param("hole_d", thread_d, "mounting hole")
    builder.param("sink", 0.6, "tooth root overlap into the body")

    lines = [
        "module tooth(x0) {",
        "  /* 20 deg flank profile, sunk into the body for a positive overlap */",
        "  translate([x0, 0, " + names["t"] + " - sink])",
        "    linear_extrude(height = " + names["h"] + " - " + names["t"] + " + sink)",
        "      polygon(points = [[-root_w / 2, 0], [root_w / 2, 0],",
        "                        [tip_w / 2, " + names["h"] + " - " + names["t"] + "],",
        "                        [-tip_w / 2, " + names["h"] + " - " + names["t"] + "]]);",
        "}",
        "",
        "difference() {",
        "  union() {",
        "    cube([" + names["l"] + ", " + names["w"] + ", " + names["t"] + "]);",
        "    for (i = [0 : " + str(teeth) + " - 1])",
        "      tooth((i + 0.5) * pitch + (tooth_span - " + str(teeth) + " * pitch) / 2);",
        "  }",
    ]
    if holes:
        if holes == 1:
            positions = [length / 2]
        else:
            step = (length - 2 * margin) / (holes - 1)
            positions = [margin + step * index_hole for index_hole in range(holes)]
        for position in positions:
            lines.append(
                f"  translate([{fmt(position)}, {fmt(width / 2)}, -1]) "
                f"cylinder(h = {names['t']} + 2, d = hole_d);"
            )
    lines.append("}")
    builder.assignment(f"tooth_span = {fmt(round(teeth * pitch, 3))};")
    builder.section("\n".join(lines))
    code = builder.render()

    bbox = (float(length), float(width), float(height))
    features_ru = [
        f"модуль {fmt(module_m)}, {teeth} зубьев, шаг {fmt(pitch, 3)} мм",
        f"высота зуба {fmt(module_m)} мм, тело рейки {fmt(body_h)} мм",
    ]
    features_en = [
        f"module {fmt(module_m)}, {teeth} teeth, {fmt(pitch, 3)} mm pitch",
        f"{fmt(module_m)} mm addendum, {fmt(body_h)} mm rack body",
    ]
    if holes:
        features_ru.append(f"{ru_count(holes, 'крепёжное отверстие', 'крепёжных отверстия', 'крепёжных отверстий')} {fmt(thread_d)} мм снизу")
        features_en.append(f"{en_count(holes)} {fmt(thread_d)} mm mounting holes from below")
    return _finish(
        rng,
        family="racks",
        variant=f"m{fmt(module_m)}" + ("_holes" if holes else ""),
        code=code,
        bbox=bbox,
        params={"module": module_m, "teeth": teeth, "pitch": round(pitch, 3), "length": length, "width": width, "height": height},
        ru_nouns=RACK_RU,
        en_nouns=RACK_EN,
        features_ru=features_ru,
        features_en=features_en,
    )


